function setLanguage(lang) {
  document.body.dataset.lang = lang;
  document.documentElement.lang = lang;

  const els = document.querySelectorAll("[data-i18n]");
  els.forEach((el) => {
    const keys = el.dataset.i18n.split(".");
    let value = translations;
    for (const key of keys) {
      value = value[key];
      if (!value) return;
    }
    el.textContent = value[lang] || value.es;
  });

  const page = document.body.dataset.page;
  document.title = pageTitles[page][lang] || pageTitles[page].es;

  const meta = document.querySelector('meta[name="description"]');
  if (meta && pageMetaDescriptions[page]) {
    meta.setAttribute("content", pageMetaDescriptions[page][lang] || pageMetaDescriptions[page].es);
  }

  document.querySelectorAll("[data-lang-btn]").forEach((btn) => {
    btn.textContent = lang === "es" ? "English" : "Español";
    btn.setAttribute("data-lang-btn", lang === "es" ? "en" : "es");
  });
}

function bindLanguageButtons() {
  document.querySelectorAll("[data-lang-btn]").forEach((button) => {
    button.addEventListener("click", () => {
      const nextLang = button.getAttribute("data-lang-btn") === "en" ? "en" : "es";
      setLanguage(nextLang);
    });
  });
}

function bindMobileNav() {
  const toggle = document.querySelector(".nav-toggle");
  const nav = document.querySelector(".site-nav");
  if (!toggle || !nav) return;

  toggle.addEventListener("click", () => {
    const open = nav.classList.toggle("is-open");
    toggle.setAttribute("aria-expanded", String(open));
  });

  nav.querySelectorAll("a").forEach((link) => {
    link.addEventListener("click", () => {
      nav.classList.remove("is-open");
      toggle.setAttribute("aria-expanded", "false");
    });
  });
}

function bindScrollHeader() {
  const header = document.querySelector(".site-header");
  if (!header) return;

  const onScroll = () => {
    header.classList.toggle("scrolled", window.scrollY > 18);
  };

  window.addEventListener("scroll", onScroll, { passive: true });
  onScroll();
}

function bindForm() {
  const form = document.querySelector(".contact-form");
  if (!form) return;

  form.addEventListener("submit", (event) => {
    event.preventDefault();
  });
}

document.addEventListener("DOMContentLoaded", () => {
  bindLanguageButtons();
  bindMobileNav();
  bindScrollHeader();
  bindForm();
  setLanguage("es");
});
